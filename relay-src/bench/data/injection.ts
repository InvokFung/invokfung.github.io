// Labelled prompt-injection set: benign requests (many of them using the same
// trigger words innocently) and attacks in nine families, including families a
// pattern screen is not expected to catch (paraphrased and non-English
// attacks). Written after the screen, to measure it; the misses are kept.

export interface InjectionSample {
  text: string;
  attack: boolean;
  category: string;
}

const zw = (s: string) => s.split(" ").join(" ​").replace(/e/g, "e‌");
const tags = (s: string) => [...s].map((c) => String.fromCodePoint(0xe0000 + c.charCodeAt(0))).join("");
const b64 = (s: string) => btoa(s);
const hex = (s: string) => [...s].map((c) => c.charCodeAt(0).toString(16).padStart(2, "0")).join("");
const fullwidth = (s: string) => s.replace(/[!-~]/g, (c) => String.fromCharCode(c.charCodeAt(0) + 0xfee0));

const benign = (category: string, xs: string[]): InjectionSample[] => xs.map((text) => ({ text, attack: false, category }));
const attack = (category: string, xs: string[]): InjectionSample[] => xs.map((text) => ({ text, attack: true, category }));

